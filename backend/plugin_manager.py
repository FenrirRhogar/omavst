"""Unified plugin list plus disable / enable / remove actions.

How each action works, and why it is safe to undo:

Native plugins (~/.vst3, ~/.clap, ~/.lv2, ~/.vst)
  disable  move the bundle to ~/.local/share/omavst/disabled/
  enable   move it back to where it was
  remove   send it to the desktop Trash (``gio trash``), so it can be restored

Windows plugins (bridged with yabridge)
  disable  ``yabridgectl blacklist add <windows file>`` and delete the bridged
           copy in ~/.vst3/yabridge. The copy is only yabridge's loader plus a
           symlink, regenerated by ``yabridgectl sync``; the Windows plugin
           itself is not touched.
  enable   ``yabridgectl blacklist rm`` then ``yabridgectl sync``
  remove   Trash the Windows plugin file and delete the bridged copy. This
           removes the plugin files only: presets, licences and registry entries
           stay, so a vendor uninstaller is still the cleaner way to uninstall.

A blacklisted plugin disappears from ``yabridgectl status``, so disabled
plugins are tracked in disabled.json next to the stored bundles.

Clients only ever pass a plugin ``id`` from the current list. Paths are always
looked up server-side and checked against the known plugin folders before
anything is moved or deleted.
"""

from __future__ import annotations

import json
import mmap
import os
import shutil
import time
from pathlib import Path
from typing import Any

try:
    from . import crash_watch, reaper, vst_scanner
    from .common import DATA_DIR, CommandError, error, private_dir, run_command, write_private
except ImportError:  # executed as a script
    import crash_watch
    import reaper
    import vst_scanner
    from common import DATA_DIR, CommandError, error, private_dir, run_command, write_private

DISABLED_DIR = DATA_DIR / "disabled"
STATE_FILE = DATA_DIR / "disabled.json"


class ActionError(Exception):
    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.err = error(code, message)


# --- disabled-plugin state ---------------------------------------------------

def _load_state() -> list[dict[str, Any]]:
    try:
        data = json.loads(STATE_FILE.read_text())
        return [p for p in data.get("plugins", []) if isinstance(p, dict) and "id" in p]
    except FileNotFoundError:
        return []
    except (OSError, ValueError):
        # Never silently drop the record of where disabled plugins went.
        raise ActionError("bad_state", f"cannot read {STATE_FILE}; fix or remove it by hand")


def _save_state(entries: list[dict[str, Any]]) -> None:
    private_dir(DATA_DIR)
    write_private(STATE_FILE, json.dumps({"version": 1, "plugins": entries}, indent=2))


# --- path safety -------------------------------------------------------------

def _inside(path: str | Path, root: str | Path) -> bool:
    """True if ``path`` is strictly below ``root`` (no symlink resolution of
    the leaf, so a symlinked plugin is handled as the link itself)."""
    p = Path(os.path.abspath(path))
    r = Path(os.path.abspath(os.path.expanduser(root)))
    return p != r and r in p.parents


def _bridged_path(plugin: dict[str, Any], install_dirs: dict[str, str]) -> str | None:
    """Where yabridge put the Linux-side copy of a Windows plugin."""
    root = install_dirs.get(plugin.get("format") or "")
    if not root:
        return None
    rel = plugin["relativePath"]
    if plugin.get("format") == "VST2" and rel.lower().endswith(".dll"):
        rel = rel[:-4] + ".so"
    return os.path.join(root, rel)


# --- unified list ------------------------------------------------------------

def inventory(config: dict[str, Any]) -> dict[str, Any]:
    """Scan everything and return one flat, sorted plugin list."""
    scan = vst_scanner.scan(config)
    yab, native = scan["yabridge"], scan["native"]
    try:
        disabled = _load_state()
        state_error = None
    except ActionError as exc:
        disabled, state_error = [], exc.err
    disabled_ids = {d["id"] for d in disabled}

    plugins: list[dict[str, Any]] = []
    if yab.get("ok"):
        for d in yab["watchedDirectories"]:
            for p in d["plugins"]:
                pid = "windows:" + p["path"]
                if pid in disabled_ids:
                    continue  # blacklist edited back by hand; the record wins
                plugins.append({
                    "id": pid,
                    "name": p["name"],
                    "format": p["format"],
                    "source": "windows",
                    "status": "active" if p["synced"] else "unsynced",
                    "path": p["path"],
                    "bridgedPath": _bridged_path(p, yab["installDirs"]),
                })
    for p in native.get("plugins", []):
        plugins.append({
            "id": "native:" + p["path"],
            "name": p["name"],
            "format": p["format"],
            "source": "native",
            "status": "active",
            "path": p["path"],
        })
    for d in disabled:
        plugins.append({
            "id": d["id"],
            "name": d["name"],
            "format": d.get("format"),
            "source": d["source"],
            "status": "disabled",
            "path": d["originalPath"],
            "disabledAt": d.get("disabledAt"),
        })
    # Display names and vendors from REAPER's cache; crash counts from crash watch.
    cache = reaper.read_cache()
    crashes = crash_watch.crashes()
    for p in plugins:
        info = cache.get(reaper.cache_key(p["path"]))
        if info:
            p["displayName"] = info["displayName"]
            p["vendor"] = info["vendor"]
            p["instrument"] = info["instrument"]
        hit = crashes.get(p["name"]) or (info and crashes.get(info["displayName"]))
        if hit and p["source"] == "windows":
            p["crashes"] = hit["count"]
    plugins.sort(key=lambda p: (p["name"].lower(), p["source"]))

    counts = {"windows": 0, "native": 0, "unsynced": 0, "disabled": 0}
    for p in plugins:
        if p["status"] == "disabled":
            counts["disabled"] += 1
        else:
            counts[p["source"]] += 1
            if p["status"] == "unsynced":
                counts["unsynced"] += 1

    result = {"plugins": plugins, "counts": counts, "yabridge": yab, "native": native}
    if state_error:
        result["stateError"] = state_error
    return result


def _find(config: dict[str, Any], plugin_id: str) -> tuple[dict[str, Any], dict[str, Any]]:
    inv = inventory(config)
    if "stateError" in inv:
        raise ActionError(inv["stateError"]["code"], inv["stateError"]["message"])
    for p in inv["plugins"]:
        if p["id"] == plugin_id:
            return p, inv
    raise ActionError("not_found", "that plugin is no longer in the list; refresh and try again")


def _check_paths(plugin: dict[str, Any], inv: dict[str, Any], config: dict[str, Any]) -> None:
    """Refuse to act on anything outside the folders we scan."""
    if plugin["source"] == "native":
        roots = config.get("native", {}).get("scanDirs", [])
        ok = any(_inside(plugin["path"], r) for r in roots)
    else:
        watched = [d["path"] for d in inv["yabridge"].get("watchedDirectories", [])]
        ok = any(_inside(plugin["path"], r) for r in watched)
        bridged = plugin.get("bridgedPath")
        installs = inv["yabridge"].get("installDirs", {}).values()
        if bridged and not any(_inside(bridged, r) for r in installs):
            ok = False
    if not ok:
        raise ActionError("unsafe_path", f"refusing to touch {plugin['path']}: outside the plugin folders")


def _delete_bridged(path: str | None) -> None:
    if not path or not os.path.lexists(path):
        return
    if os.path.isdir(path) and not os.path.islink(path):
        shutil.rmtree(path)
    else:
        os.unlink(path)


def _trash(path: str, timeout: float) -> None:
    try:
        run_command(["gio", "trash", "--", path], timeout=timeout)
    except CommandError as exc:
        raise ActionError(exc.err["code"], f"could not move {path} to Trash: {exc.err['message']}")


# --- actions -----------------------------------------------------------------

def disable(config: dict[str, Any], plugin_id: str) -> dict[str, Any]:
    plugin, inv = _find(config, plugin_id)
    if plugin["status"] == "disabled":
        raise ActionError("already_disabled", f"{plugin['name']} is already disabled")
    _check_paths(plugin, inv, config)
    timeout = config.get("commands", {}).get("timeoutSeconds", 10)
    entry = {
        "id": plugin["id"],
        "name": plugin["name"],
        "format": plugin["format"],
        "source": plugin["source"],
        "originalPath": plugin["path"],
        "disabledAt": time.time(),
    }

    if plugin["source"] == "native":
        private_dir(DATA_DIR)
        dest_dir = DISABLED_DIR / (plugin["format"] or "other")
        dest_dir.mkdir(parents=True, exist_ok=True)
        dest = dest_dir / Path(plugin["path"]).name
        n = 1
        while os.path.lexists(dest):
            dest = dest_dir / f"{Path(plugin['path']).stem}-{n}{Path(plugin['path']).suffix}"
            n += 1
        # Record first: if the move fails we drop the record again, but a move
        # that succeeds is never left without one.
        entry["storedPath"] = str(dest)
        state = _load_state()
        _save_state(state + [entry])
        try:
            shutil.move(plugin["path"], dest)
        except OSError as exc:
            _save_state(state)
            raise ActionError("move_failed", f"could not move {plugin['name']}: {exc}")
    else:
        try:
            run_command(["yabridgectl", "blacklist", "add", plugin["path"]], timeout=timeout)
        except CommandError as exc:
            raise ActionError(exc.err["code"], f"yabridgectl blacklist failed: {exc.err['message']}")
        _save_state(_load_state() + [entry])
        try:
            _delete_bridged(plugin.get("bridgedPath"))
        except OSError as exc:
            raise ActionError("delete_failed", f"disabled, but could not delete the bridged copy: {exc}")

    return {"ok": True, "message": f"Disabled {plugin['name']}", **reaper.forget([plugin["path"]])}


def enable(config: dict[str, Any], plugin_id: str) -> dict[str, Any]:
    plugin, _ = _find(config, plugin_id)
    if plugin["status"] != "disabled":
        raise ActionError("not_disabled", f"{plugin['name']} is not disabled")
    state = _load_state()
    entry = next(e for e in state if e["id"] == plugin_id)
    rest = [e for e in state if e["id"] != plugin_id]
    timeout = config.get("commands", {}).get("timeoutSeconds", 10)

    if entry["source"] == "native":
        stored, original = entry.get("storedPath"), entry["originalPath"]
        if not stored or not os.path.lexists(stored):
            _save_state(rest)
            raise ActionError("missing", f"the stored copy of {entry['name']} is gone; removed it from the list")
        if os.path.lexists(original):
            raise ActionError("exists", f"{original} already exists; move it away first")
        if not _inside(stored, DISABLED_DIR):
            raise ActionError("unsafe_path", f"refusing to move {stored}: not in the disabled folder")
        Path(original).parent.mkdir(parents=True, exist_ok=True)
        try:
            shutil.move(stored, original)
        except OSError as exc:
            raise ActionError("move_failed", f"could not restore {entry['name']}: {exc}")
        _save_state(rest)
        return {"ok": True, "message": f"Enabled {entry['name']}", **reaper.startup_note()}

    try:
        listed = run_command(["yabridgectl", "blacklist", "list"], timeout=timeout)
        if entry["originalPath"] in listed:
            run_command(["yabridgectl", "blacklist", "rm", entry["originalPath"]], timeout=timeout)
    except CommandError as exc:
        raise ActionError(exc.err["code"], f"yabridgectl blacklist failed: {exc.err['message']}")
    _save_state(rest)
    synced = vst_scanner.yabridge_sync(timeout=max(120, timeout))
    if not synced["ok"]:
        return {"ok": False, "error": error("sync_failed", f"enabled {entry['name']}, but sync failed: "
                                                         f"{synced['error']['message']}")}
    return {"ok": True, "message": f"Enabled {entry['name']}", **reaper.startup_note()}


def remove(config: dict[str, Any], plugin_id: str) -> dict[str, Any]:
    plugin, inv = _find(config, plugin_id)
    timeout = config.get("commands", {}).get("timeoutSeconds", 10)

    if plugin["status"] == "disabled":
        state = _load_state()
        entry = next(e for e in state if e["id"] == plugin_id)
        rest = [e for e in state if e["id"] != plugin_id]
        if entry["source"] == "native":
            stored = entry.get("storedPath")
            if stored and os.path.lexists(stored):
                if not _inside(stored, DISABLED_DIR):
                    raise ActionError("unsafe_path", f"refusing to trash {stored}")
                _trash(stored, timeout)
        else:
            if os.path.lexists(entry["originalPath"]):
                watched = [d["path"] for d in inv["yabridge"].get("watchedDirectories", [])]
                if not any(_inside(entry["originalPath"], r) for r in watched):
                    raise ActionError("unsafe_path", f"refusing to trash {entry['originalPath']}")
                _trash(entry["originalPath"], timeout)
            try:
                run_command(["yabridgectl", "blacklist", "rm", entry["originalPath"]], timeout=timeout)
            except CommandError:
                pass  # already off the blacklist; nothing left to undo
        _save_state(rest)
        return {"ok": True, "message": f"Moved {entry['name']} to Trash", **reaper.forget([entry["originalPath"]])}

    _check_paths(plugin, inv, config)
    _trash(plugin["path"], timeout)
    if plugin["source"] == "windows":
        try:
            _delete_bridged(plugin.get("bridgedPath"))
        except OSError as exc:
            raise ActionError("delete_failed", f"trashed, but could not delete the bridged copy: {exc}")
    return {"ok": True, "message": f"Moved {plugin['name']} to Trash", **reaper.forget([plugin["path"]])}


# --- details -----------------------------------------------------------------

_PE_KEYS = ("CompanyName", "FileVersion", "ProductVersion", "ProductName")


def _pe_strings(path: str) -> dict[str, str]:
    """Read VERSIONINFO strings from a Windows binary without a PE parser:
    the StringFileInfo block stores ``Key\\0`` then the value, both UTF-16LE,
    with the value 32-bit aligned.

    PACE-protected plugins (iLok) carry PACE's own version block too, often
    after the plugin's. Blocks are matched up by position and PACE's are
    skipped; a fully wrapped plugin then simply reports no version.
    """
    def read_value(mm: mmap.mmap, j: int, limit: int) -> str:
        while j < limit - 1 and mm[j:j + 2] == b"\0\0":
            j += 2  # alignment padding
        end = j
        while end < min(limit - 1, j + 256) and mm[end:end + 2] != b"\0\0":
            end += 2
        return mm[j:end].decode("utf-16-le", errors="replace").strip()

    blocks: list[dict[str, str]] = []
    marker = "StringFileInfo".encode("utf-16-le")
    try:
        with open(path, "rb") as f, mmap.mmap(f.fileno(), 0, access=mmap.ACCESS_READ) as mm:
            i = mm.find(marker)
            while i >= 0:
                nxt = mm.find(marker, i + 1)
                limit = min(len(mm), i + 4096, nxt if nxt >= 0 else len(mm))
                block = {}
                for key in _PE_KEYS:
                    k = mm.find((key + "\0").encode("utf-16-le"), i, limit)
                    if k >= 0:
                        value = read_value(mm, k + 2 * (len(key) + 1), limit)
                        if value:
                            block[key] = value
                if block:
                    blocks.append(block)
                i = nxt
    except (OSError, ValueError):
        return {}
    for block in blocks:
        if "PACE Anti-Piracy" not in block.get("CompanyName", ""):
            return block
    return {}


def _windows_binary(path: str) -> str | None:
    """The DLL inside a Windows plugin: the file itself, or inside a bundle."""
    p = Path(path)
    if p.is_file():
        return str(p)
    win = p / "Contents" / "x86_64-win"
    for f in sorted(win.glob("*")) if win.is_dir() else []:
        if f.is_file():
            return str(f)
    return None


def _moduleinfo(path: str) -> dict[str, Any]:
    """VST3 SDK 3.7.5+ bundles describe themselves in moduleinfo.json."""
    f = Path(path) / "Contents" / "Resources" / "moduleinfo.json"
    try:
        # moduleinfo.json is JSON5-ish (trailing commas); try plain JSON first.
        text = f.read_text(errors="replace")
        try:
            data = json.loads(text)
        except ValueError:
            import re
            data = json.loads(re.sub(r",(\s*[}\]])", r"\1", text))
        info = data.get("Factory Info", {})
        return {"version": data.get("Version"), "vendor": info.get("Vendor")}
    except (OSError, ValueError, AttributeError):
        return {}


def _size(path: str) -> int:
    p = Path(path)
    if p.is_file():
        return p.stat().st_size
    total = 0
    for dirpath, _, files in os.walk(p):
        for name in files:
            try:
                total += os.lstat(os.path.join(dirpath, name)).st_size
            except OSError:
                pass
    return total


def details(config: dict[str, Any], plugin_id: str) -> dict[str, Any]:
    try:
        plugin, _ = _find(config, plugin_id)
    except ActionError as exc:
        return {"ok": False, "error": exc.err}
    path = plugin["path"]
    if plugin["status"] == "disabled" and plugin["source"] == "native":
        entry = next((e for e in _load_state() if e["id"] == plugin_id), {})
        path = entry.get("storedPath", path)
    out: dict[str, Any] = {"ok": True, "id": plugin_id, "path": plugin["path"]}
    if not os.path.lexists(path):
        out["missing"] = True
        return out
    out["size"] = _size(path)
    out["modified"] = os.path.getmtime(path)
    if plugin.get("bridgedPath"):
        out["bridgedPath"] = plugin["bridgedPath"]
    info = _moduleinfo(path) if os.path.isdir(path) else {}
    if plugin["source"] == "windows":
        binary = _windows_binary(path)
        pe = _pe_strings(binary) if binary else {}
        info.setdefault("version", pe.get("ProductVersion") or pe.get("FileVersion"))
        if not info.get("version"):
            info["version"] = pe.get("ProductVersion") or pe.get("FileVersion")
        info["vendor"] = info.get("vendor") or pe.get("CompanyName")
        info["product"] = pe.get("ProductName")
    out.update({k: v for k, v in info.items() if v})
    out["vendor"] = out.get("vendor") or plugin.get("vendor")
    return out


ACTIONS = {"disable": disable, "enable": enable, "remove": remove}


def run_action(config: dict[str, Any], name: str, plugin_id: str) -> dict[str, Any]:
    """Run one action; never raises."""
    try:
        return ACTIONS[name](config, plugin_id)
    except ActionError as exc:
        return {"ok": False, "error": exc.err}
    except OSError as exc:
        return {"ok": False, "error": error("os_error", str(exc))}


